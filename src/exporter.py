# 3. WORD (.DOCX) EXPORT
# ═════════════════════════════════════════════════════════
def export_docx(title, subtitle, headers, rows_data, institution="Slotify Institute of Technology"):
    """Generate a clean Word (.docx) document using python-docx."""
    if not HAS_DOCX:
        raise ImportError("python-docx is not installed.")

    doc = docx.Document()

    # Document Header
    p_inst = doc.add_paragraph()
    p_inst.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run_inst = p_inst.add_run(f"{institution}\n")
    run_inst.font.name = "Calibri"
    run_inst.font.size = Pt(14)
    run_inst.font.bold = True
    run_inst.font.color.rgb = RGBColor(0x1E, 0x3D, 0x2F)

    run_title = p_inst.add_run(f"{title}\n")
    run_title.font.name = "Calibri"
    run_title.font.size = Pt(12)
    run_title.font.bold = True
    run_title.font.color.rgb = RGBColor(0x31, 0x5C, 0x45)

    run_meta = p_inst.add_run(f"{subtitle} | Generated by Slotify 🗓️ on {datetime.now().strftime('%d %B %Y')}")
    run_meta.font.name = "Calibri"
    run_meta.font.size = Pt(8.5)
    run_meta.font.italic = True
    run_meta.font.color.rgb = RGBColor(0x55, 0x5E, 0x52)

    doc.add_paragraph() # Spacing

    # Table
    table = doc.add_table(rows=1, cols=len(headers))
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.style = 'Table Grid'

    hdr_cells = table.rows[0].cells
    for i, h in enumerate(headers):
        hdr_cells[i].text = h
        p = hdr_cells[i].paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        for run in p.runs:
            run.font.bold = True
            run.font.size = Pt(9)

    for r_idx, row in enumerate(rows_data):
        row_cells = table.add_row().cells
        row_cells[0].text = row['day']
        p0 = row_cells[0].paragraphs[0]
        p0.alignment = WD_ALIGN_PARAGRAPH.CENTER
        if p0.runs:
            p0.runs[0].font.bold = True

        for s_idx, slot in enumerate(row['slots']):
            is_recess = slot.get('isRecess', False)
            txt = slot.get('text', '')
            room = slot.get('room', '')
            teacher = slot.get('teacher', '')
            sub = slot.get('subject', txt)

            cell_p = row_cells[s_idx + 1].paragraphs[0]
            cell_p.alignment = WD_ALIGN_PARAGRAPH.CENTER

            if is_recess:
                r = cell_p.add_run("RECESS")
                r.font.italic = True
                r.font.size = Pt(8.5)
            elif txt:
                content = sub
                if teacher:
                    content += f" ({teacher})"
                if room:
                    content += f" [{room}]"
                r = cell_p.add_run(content)
                r.font.size = Pt(8.5)
                if slot.get('isLab'):
                    r.font.bold = True
            else:
                r = cell_p.add_run("—")
                r.font.size = Pt(8.5)

    buffer = io.BytesIO()
    doc.save(buffer)
    buffer.seek(0)
    return buffer


