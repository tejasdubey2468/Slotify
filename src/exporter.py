# 2. EXCEL (.XLSX) EXPORT
# ═════════════════════════════════════════════════════════
def export_excel(title, subtitle, headers, rows_data, institution="Slotify Institute of Technology"):
    """Generate a formatted Excel (.xlsx) spreadsheet using OpenPyXL."""
    if not HAS_OPENPYXL:
        raise ImportError("openpyxl is not installed.")

    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Timetable"
    ws.views.sheetView[0].showGridLines = True

    # Styling definitions
    font_inst = Font(name="Calibri", size=14, bold=True, color="1E3D2F")
    font_title = Font(name="Calibri", size=11, bold=True, color="315C45")
    font_meta = Font(name="Calibri", size=9, italic=True, color="555E52")
    font_hdr = Font(name="Calibri", size=10, bold=True, color="FFFFFF")
    font_day = Font(name="Calibri", size=10, bold=True, color="1E3D2F")
    font_data = Font(name="Calibri", size=9, color="292E27")
    font_lab = Font(name="Calibri", size=9, bold=True, color="9C5B32")
    font_recess = Font(name="Calibri", size=9, italic=True, color="8A6D3B")

    fill_hdr = PatternFill("solid", fgColor="315C45")
    fill_recess = PatternFill("solid", fgColor="FBF6E8")
    fill_lab = PatternFill("solid", fgColor="FAF1EB")
    fill_alt = PatternFill("solid", fgColor="F9F7F3")

    border_thin = Border(
        left=Side(style='thin', color='D5CCC0'),
        right=Side(style='thin', color='D5CCC0'),
        top=Side(style='thin', color='D5CCC0'),
        bottom=Side(style='thin', color='D5CCC0')
    )

    align_center = Alignment(horizontal='center', vertical='center', wrap_text=True)
    align_left = Alignment(horizontal='left', vertical='center')

    # Row 1: Institution
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=len(headers))
    cell_inst = ws.cell(row=1, column=1, value=f"{institution}")
    cell_inst.font = font_inst
    cell_inst.alignment = align_center

    # Row 2: Title
    ws.merge_cells(start_row=2, start_column=1, end_row=2, end_column=len(headers))
    cell_t = ws.cell(row=2, column=1, value=title)
    cell_t.font = font_title
    cell_t.alignment = align_center

    # Row 3: Subtitle / Timestamp
    ws.merge_cells(start_row=3, start_column=1, end_row=3, end_column=len(headers))
    cell_sub = ws.cell(row=3, column=1, value=f"{subtitle} | Generated by Slotify 🗓️ on {datetime.now().strftime('%d %B %Y, %I:%M %p')}")
    cell_sub.font = font_meta
    cell_sub.alignment = align_center

    # Row 5: Table Header
    for col_idx, h in enumerate(headers, 1):
        c = ws.cell(row=5, column=col_idx, value=h)
        c.font = font_hdr
        c.fill = fill_hdr
        c.alignment = align_center
        c.border = border_thin
    ws.row_dimensions[5].height = 26

    # Rows 6+: Data rows
    curr_row = 6
    for r_idx, row in enumerate(rows_data):
        day_val = row['day']
        c_day = ws.cell(row=curr_row, column=1, value=day_val)
        c_day.font = font_day
        c_day.alignment = align_center
        c_day.border = border_thin
        if r_idx % 2 == 1:
            c_day.fill = fill_alt

        for s_idx, slot in enumerate(row['slots'], 2):
            is_recess = slot.get('isRecess', False)
            is_lab = slot.get('isLab', False)
            txt = slot.get('text', '')
            room = slot.get('room', '')
            teacher = slot.get('teacher', '')
            sub = slot.get('subject', txt)

            c_slot = ws.cell(row=curr_row, column=s_idx)
            c_slot.alignment = align_center
            c_slot.border = border_thin

            if is_recess:
                c_slot.value = "RECESS"
                c_slot.font = font_recess
                c_slot.fill = fill_recess
            elif is_lab:
                val = f"{sub}\n{teacher}"
                if room:
                    val += f" [{room}]"
                c_slot.value = val
                c_slot.font = font_lab
                c_slot.fill = fill_lab
            elif txt:
                val = sub
                if teacher:
                    val += f" ({teacher})"
                if room:
                    val += f"\n[{room}]"
                c_slot.value = val
                c_slot.font = font_data
                if r_idx % 2 == 1:
                    c_slot.fill = fill_alt
            else:
                c_slot.value = "—"
                c_slot.font = font_meta
                if r_idx % 2 == 1:
                    c_slot.fill = fill_alt

        ws.row_dimensions[curr_row].height = 36
        curr_row += 1

    # Column widths
    ws.column_dimensions['A'].width = 12
    for c_letter in ['B', 'C', 'D', 'E', 'F', 'G', 'H']:
        ws.column_dimensions[c_letter].width = 18

    buffer = io.BytesIO()
    wb.save(buffer)
    buffer.seek(0)
    return buffer


