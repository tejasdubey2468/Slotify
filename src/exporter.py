# 1. PDF EXPORT
# ═════════════════════════════════════════════════════════
def export_pdf(title, subtitle, headers, rows_data, institution="Slotify Institute of Technology"):
    """Generate a clean, publication-ready PDF timetable using ReportLab."""
    if not HAS_REPORTLAB:
        raise ImportError("reportlab is not installed.")

    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=landscape(A4),
        leftMargin=24,
        rightMargin=24,
        topMargin=24,
        bottomMargin=24
    )

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Heading1'],
        fontName='Helvetica-Bold',
        fontSize=15,
        leading=18,
        textColor=colors.HexColor('#1E3D2F'),
        alignment=1, # Center
        spaceAfter=3
    )
    sub_style = ParagraphStyle(
        'DocSubtitle',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=9,
        leading=12,
        textColor=colors.HexColor('#555E52'),
        alignment=1,
        spaceAfter=12
    )
    cell_style = ParagraphStyle(
        'CellText',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=7.5,
        leading=9.5,
        alignment=1,
        textColor=colors.HexColor('#292E27')
    )
    cell_bold_style = ParagraphStyle(
        'CellBold',
        parent=cell_style,
        fontName='Helvetica-Bold',
        textColor=colors.HexColor('#1E3D2F')
    )
    cell_lab_style = ParagraphStyle(
        'CellLab',
        parent=cell_style,
        fontName='Helvetica-Bold',
        textColor=colors.HexColor('#9C5B32')
    )
    cell_recess_style = ParagraphStyle(
        'CellRecess',
        parent=cell_style,
        fontName='Helvetica-Oblique',
        textColor=colors.HexColor('#6B5A2E')
    )

    story = []
    # Header branding
    story.append(Paragraph(f"<b>{institution}</b> — {title}", title_style))
    story.append(Paragraph(f"{subtitle} | Generated by Slotify 🗓️ on {datetime.now().strftime('%d %B %Y, %I:%M %p')}", sub_style))

    # Prepare table matrix
    table_matrix = []
    # Header row
    hdr_cells = [Paragraph(f"<b>{h}</b>", ParagraphStyle('Hdr', parent=cell_bold_style, textColor=colors.HexColor('#FFFFFF'), fontSize=8)) for h in headers]
    table_matrix.append(hdr_cells)

    recess_col_idx = 5 # 1-based index (Day=0, slot1=1, slot2=2, slot3=3, slot4=4, slot5=recess=5)

    for row in rows_data:
        day_cell = Paragraph(f"<b>{row['day']}</b>", cell_bold_style)
        cells = [day_cell]
        for idx, s in enumerate(row['slots']):
            is_recess = s.get('isRecess', False)
            is_lab = s.get('isLab', False)
            txt = s.get('text', '')
            room = s.get('room', '')

            if is_recess:
                cells.append(Paragraph("RECESS", cell_recess_style))
            elif is_lab:
                display = f"<b>{s.get('subject','LAB')}</b><br/><font size=6 color='#774422'>{s.get('teacher','')} | {room}</font>"
                cells.append(Paragraph(display, cell_lab_style))
            elif txt:
                sub = s.get('subject', txt)
                teacher = s.get('teacher', '')
                display = f"<b>{sub}</b>"
                if teacher:
                    display += f"<br/><font size=6 color='#555555'>{teacher}</font>"
                if room:
                    display += f"<br/><font size=5.5 color='#315C45'>[{room}]</font>"
                cells.append(Paragraph(display, cell_style))
            else:
                cells.append(Paragraph("—", ParagraphStyle('Empty', parent=cell_style, textColor=colors.HexColor('#AAAAAA'))))
        table_matrix.append(cells)

    # Column widths calculation: A4 landscape width ~842pt, margins 48pt total -> ~794pt
    col_w = [54] + [(740 / (len(headers) - 1))] * (len(headers) - 1)

    t = Table(table_matrix, colWidths=col_w, repeatRows=1)
    t_style = [
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#315C45')),
        ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#D5CCC0')),
        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.HexColor('#FFFFFF'), colors.HexColor('#FAF7F2')]),
        ('TOPPADDING', (0, 0), (-1, -1), 4),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
    ]

    # Style recess column if 7 slots
    if len(headers) == 8:
        t_style.append(('BACKGROUND', (5, 1), (5, -1), colors.HexColor('#FBF6E8')))

    t.setStyle(TableStyle(t_style))
    story.append(t)

    # Signatures block
    story.append(Spacer(1, 24))
    sig_matrix = [
        [
            Paragraph("<b>Timetable Coordinator</b><br/><font size=7 color='#777'>Department of Computer Engineering</font>", cell_style),
            Paragraph("<b>Head of Department (H.O.D.)</b><br/><font size=7 color='#777'>Academic Year 2026–2027</font>", cell_style),
            Paragraph("<b>Principal / Dean Academic</b><br/><font size=7 color='#777'>Slotify Institute of Technology</font>", cell_style)
        ]
    ]
    sig_table = Table(sig_matrix, colWidths=[260, 260, 260])
    sig_table.setStyle(TableStyle([
        ('LINEABOVE', (0, 0), (-1, 0), 1, colors.HexColor('#CCD5CD')),
        ('TOPPADDING', (0, 0), (-1, 0), 10),
        ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
    ]))
    story.append(sig_table)

    doc.build(story)
    buffer.seek(0)
    return buffer


