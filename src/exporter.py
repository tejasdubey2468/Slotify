# 4. CSV (.CSV) EXPORT
# ═════════════════════════════════════════════════════════
def export_csv(title, headers, rows_data):
    """Generate a clean RFC-4180 CSV export."""
    buffer = io.StringIO()
    writer = csv.writer(buffer)

    # Title header comment
    writer.writerow([f"# {title} - Generated by Slotify 🗓️ on {datetime.now().strftime('%Y-%m-%d %H:%M')}"])
    writer.writerow(headers)

    for row in rows_data:
        csv_row = [row['day']]
        for slot in row['slots']:
            is_recess = slot.get('isRecess', False)
            txt = slot.get('text', '')
            room = slot.get('room', '')
            teacher = slot.get('teacher', '')
            sub = slot.get('subject', txt)

            if is_recess:
                csv_row.append("RECESS")
            elif txt:
                item = sub
                if teacher:
                    item += f" ({teacher})"
                if room:
                    item += f" [{room}]"
                csv_row.append(item)
            else:
                csv_row.append("")
        writer.writerow(csv_row)

    output = io.BytesIO(buffer.getvalue().encode('utf-8'))
    output.seek(0)
    return output
